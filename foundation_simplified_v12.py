def _normalize_vector_notation(value):
    """Use a visible adjacent arrow; combining arrows fail in some offline fonts."""
    if isinstance(value, str):
        value = value.replace("السهم فوق", "علامة السهم بجانب")
        value = value.replace("سهمًا فوق K", "علامة سهم مع K")
        return re.sub(r"([A-Za-z])⃗", r"→\1", value)
    if isinstance(value, list):
        return [_normalize_vector_notation(item) for item in value]
    if isinstance(value, dict):
        return {key: _normalize_vector_notation(item) for key, item in value.items()}
    return value


def apply_simplification(courses):
    """Apply the v12 remedial wording and inline-equation metadata in-place."""
    lessons = {lesson["id"]: lesson for course in courses for lesson in course["lessons"]}
    missing = set(PATCHES) - set(lessons)
    if missing:
        raise KeyError(f"Missing foundation lessons: {sorted(missing)}")
    for lesson_id, source_patch in PATCHES.items():
        patch = deepcopy(source_patch)
        example_patch = patch.pop("example", {})
        lesson = lessons[lesson_id]
        lesson.update(patch)
        lesson["example"].update(example_patch)
        lesson["example"]["substitution"] = lesson["formula"]
        lesson["example"].setdefault("inline_help", "ضع كل قيمة مكان رمزها داخل العلاقة، ثم اكتب الناتج في السطر التالي.")
        for field in lesson["example"]["fields"]:
            field["placeholder"] = "…"
        lesson["example"]["result"]["placeholder"] = "…"
    for course in courses:
        if course["theme"] == "physics":
            course["subtitle"] = "نبدأ من الصفر: معنى بسيط، سهم يوضح الاتجاه، ثم تعويض داخل العلاقة نفسها."
        else:
            course["subtitle"] = "نبدأ من أمثلة يومية وصور بسيطة، ثم نعوض داخل العلاقة خطوة خطوة."
        course["source_note"] = "مبسّط علاجيًا لطلبة انقطعت عنهم الدراسة؛ لا يفترض فهمًا سابقًا مكتملًا."
    for course in courses:
        normalized = _normalize_vector_notation(course)
        course.clear()
        course.update(normalized)
    return courses
