def validate_course(course):
    required_lesson = {"id", "title", "objective", "hook", "prerequisite", "explanation", "key_points", "formula", "symbols", "visual", "example", "checkpoint", "memory", "mistake"}
    ids = []
    for lesson in course["lessons"]:
        missing = required_lesson - set(lesson)
        if missing:
            raise ValueError(f"{course['id']} {lesson.get('id')}: missing {sorted(missing)}")
        ids.append(lesson["id"])
        ex = lesson["example"]
        if not ex.get("fields") or "result" not in ex or not ex.get("solution"):
            raise ValueError(f"Incomplete example in {lesson['id']}")
        cp = lesson["checkpoint"]
        if not 0 <= cp["answer"] < len(cp["options"]):
            raise ValueError(f"Bad checkpoint answer in {lesson['id']}")
    if len(ids) != len(set(ids)):
        raise ValueError(f"Duplicate lesson id in {course['id']}")


validate_course(PHYSICS_REVIEW)
validate_course(CHEMISTRY_REVIEW)
